EMAIL_PROVIDER = os.environ.get('DJANGO_EMAIL_PROVIDER', 'console' if DEBUG else 'smtp').strip().lower()
if EMAIL_PROVIDER == 'gmail':
    EMAIL_BACKEND = 'django.core.mail.backends.smtp.EmailBackend'
    EMAIL_HOST = os.environ.get('DJANGO_EMAIL_HOST', 'smtp.gmail.com')
    EMAIL_PORT = int(os.environ.get('DJANGO_EMAIL_PORT', '587'))
    EMAIL_USE_TLS = env_bool('DJANGO_EMAIL_USE_TLS', default=True)
    EMAIL_USE_SSL = env_bool('DJANGO_EMAIL_USE_SSL', default=False)
elif EMAIL_PROVIDER == 'console':
    EMAIL_BACKEND = 'django.core.mail.backends.console.EmailBackend'
    EMAIL_HOST = os.environ.get('DJANGO_EMAIL_HOST', 'localhost')
    EMAIL_PORT = int(os.environ.get('DJANGO_EMAIL_PORT', '25'))
    EMAIL_USE_TLS = env_bool('DJANGO_EMAIL_USE_TLS')
    EMAIL_USE_SSL = env_bool('DJANGO_EMAIL_USE_SSL')
elif EMAIL_PROVIDER == 'smtp':
    EMAIL_BACKEND = os.environ.get(
        'DJANGO_EMAIL_BACKEND',
        'django.core.mail.backends.smtp.EmailBackend',
    )
    EMAIL_HOST = os.environ.get('DJANGO_EMAIL_HOST', 'localhost')
    EMAIL_PORT = int(os.environ.get('DJANGO_EMAIL_PORT', '25'))
    EMAIL_USE_TLS = env_bool('DJANGO_EMAIL_USE_TLS')
    EMAIL_USE_SSL = env_bool('DJANGO_EMAIL_USE_SSL')
else:
    raise ImproperlyConfigured(
        'DJANGO_EMAIL_PROVIDER must be one of: console, gmail, smtp.'
    )

